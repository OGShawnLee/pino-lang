  private static string Sanitize(string name) {
    if (string.IsNullOrEmpty(name)) {
      return "anon";
    }

    var sb = new StringBuilder(name.Length);
    foreach (char ch in name) {
      if ((ch >= 'a' && ch <= 'z') || (ch >= 'A' && ch <= 'Z') || (ch >= '0' && ch <= '9') || ch == '_') {
        sb.Append(ch);
      } else {
        sb.Append('_');
      }
    }

    if (sb.Length > 48) {
      sb.Length = 48;
    }

    return sb.ToString();
  }

  private string ZeroInitFor(IrTypeId id) {
    IrType t = _types.GetType(id);
    return t.Kind switch {
      IrTypeKind.Bool or IrTypeKind.Int or IrTypeKind.Rune or IrTypeKind.Enum => "0",
      IrTypeKind.Float => "0.0",
      IrTypeKind.Regex or IrTypeKind.Vector or IrTypeKind.Map or IrTypeKind.Set
          or IrTypeKind.Pool or IrTypeKind.Ptr or IrTypeKind.Cell or IrTypeKind.Env => "NULL",
      IrTypeKind.Union when t.IsRecursiveUnion => "NULL",
      _ => "{0}",
    };
  }

  private SourceText? ResolveFunctionSource(IrFunction fn) {
    if (fn.Source is not null) {
      return fn.Source;
    }

    if (fn.Name.StartsWith("__pino_init_", StringComparison.Ordinal)) {
      string mod = fn.Name["__pino_init_".Length..];
      if (_sourcesByModuleName.TryGetValue(mod, out SourceText? initSrc)) {
        return initSrc;
      }
    }

    int sep = fn.Name.IndexOf("::", StringComparison.Ordinal);
    if (sep > 0) {
      string prefix = fn.Name[..sep];
      if (_sourcesByModuleName.TryGetValue(prefix, out SourceText? modSrc)) {
        return modSrc;
      }
    }

    return _rootSource;
  }

  private static string FormatPinoLoc(SourceText? source, SourceSpan span) {
    if (source is not null && span.Start >= 0 && span.Length >= 0 && span.Start <= source.Length) {
      LinePosition lp = source.GetLineColumn(span.Start);
      string file = NormalizeDisplayPath(source.FilePath ?? "<input>");
      return string.Create(
          CultureInfo.InvariantCulture,
          $"PINO_LOC(\"{EscapeCString(file)}\", {lp.Line}, {lp.Column})");
    }

    return "PINO_LOC(\"<input>\", 0, 0)";
  }

  private void EmitLineDirectiveIfNeeded(SourceText? source, SourceSpan span, ref int lastLine, ref string? lastFile) {
    if (!_options.EmitLineDirectives || source is null || span == default) {
      return;
    }

    if (span.Start < 0 || span.Length < 0 || span.Start > source.Length) {
      return;
    }

    LinePosition lp = source.GetLineColumn(span.Start);
    string file = NormalizeDisplayPath(source.FilePath ?? "<input>");
    if (lp.Line == lastLine && string.Equals(file, lastFile, StringComparison.Ordinal)) {
      return;
    }

    lastLine = lp.Line;
    lastFile = file;
    _sb.Append("#line ").Append(lp.Line).Append(" \"").Append(EscapeCString(file)).Append("\"\n");
  }

  private static string NormalizeDisplayPath(string path) => path.Replace('\\', '/');

  private static string EscapeCString(string text) {
    byte[] bytes = s_utf8NoBom.GetBytes(text);
    var sb = new StringBuilder(bytes.Length + 8);
    AppendEscapedBytes(sb, bytes);
    return sb.ToString();
  }

  private void AppendCBytesLiteral(byte[] bytes) {
    _sb.Append('"');
    AppendEscapedBytes(_sb, bytes);
    _sb.Append('"');
  }

  private static void AppendEscapedBytes(StringBuilder sb, byte[] bytes) {
    for (int i = 0; i < bytes.Length; i++) {
      byte b = bytes[i];
      switch (b) {
        case (byte) '\\':
          sb.Append("\\\\");
          break;
        case (byte) '"':
          sb.Append("\\\"");
          break;
        case (byte) '\n':
          sb.Append("\\n");
          break;
        case (byte) '\r':
          sb.Append("\\r");
          break;
        case (byte) '\t':
          sb.Append("\\t");
          break;
        case (byte) '?' when i > 0 && bytes[i - 1] == (byte) '?':
          // Avoid C99 trigraphs (??=, ??/, etc.).
          sb.Append("\\?");
          break;
        default:
          if (b >= 0x20 && b < 0x7F) {
            sb.Append((char) b);
          } else {
            // Fixed 3-digit octal escape never consumes following hex digits.
            sb.Append('\\');
            sb.Append((char) ('0' + ((b >> 6) & 7)));
            sb.Append((char) ('0' + ((b >> 3) & 7)));
            sb.Append((char) ('0' + (b & 7)));
          }
          break;
      }
    }
  }

  private static string FormatCDoubleLiteral(double value) {
    if (double.IsNaN(value)) {
      return "(0.0 / 0.0)";
    }

    if (double.IsPositiveInfinity(value)) {
      return "(1.0 / 0.0)";
    }

    if (double.IsNegativeInfinity(value)) {
      return "(-1.0 / 0.0)";
    }

    if (value == 0.0) {
      return double.IsNegative(value) ? "(-0.0)" : "0.0";
    }

    string text = value.ToString("G17", CultureInfo.InvariantCulture);
    if (!text.Contains('.', StringComparison.Ordinal)
        && !text.Contains('e', StringComparison.Ordinal)
        && !text.Contains('E', StringComparison.Ordinal)) {
      text += ".0";
    }

    return text;
  }

  private static string FormatCInt64Literal(long value) =>
      value == long.MinValue
          ? "INT64_MIN"
          : string.Create(CultureInfo.InvariantCulture, $"{value}LL");

  private static string FormatPinoStringPoolExpr(IrModule module, int poolId) {
    int byteLen = s_utf8NoBom.GetByteCount(module.StringPool[poolId]);
    return string.Create(CultureInfo.InvariantCulture, $"((PinoString){{NULL, pstr_{poolId}, {byteLen}LL}})");
  }
