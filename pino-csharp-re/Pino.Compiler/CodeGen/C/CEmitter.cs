  private string MapEntryCName(IrTypeId id) => $"pt_mape_{id.Index}";

  private string MapStructCName(IrTypeId id) => $"pt_map_{id.Index}";

  private string SetEntryCName(IrTypeId id) => $"pt_sete_{id.Index}";

