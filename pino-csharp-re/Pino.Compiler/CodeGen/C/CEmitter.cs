  private string FuncCName(IrFuncId id) {
    string name = _module.Functions[id.Index].Name;
    string prefix = name.Contains("::", StringComparison.Ordinal) ? "pm_" : "pf_";
    return $"{prefix}{id.Index}_{Sanitize(name)}";
  }

