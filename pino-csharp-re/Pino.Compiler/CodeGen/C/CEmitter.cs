using System.Globalization;
using System.Text;

using Pino.Compiler.Checking;
using Pino.Compiler.IR;
using Pino.Compiler.IR.Passes;
using Pino.Compiler.Text;

namespace Pino.Compiler.CodeGen.C;

/// <summary>
/// Options controlling C99 emission from PIR (<c>056-re-ir-design</c> §7).
/// </summary>
public sealed record CEmitOptions(
    bool EmitLineDirectives = true,
    bool EmitFrames = true);

/// <summary>
/// Emits TCC-safe, BOM-less, GC-free C99 targeting <c>runtime-re/pino_rt.h</c> from a
/// post-RC <see cref="IrModule"/> (<c>056-re-ir-design</c> §2, §4, §7).
/// </summary>
public sealed partial class CEmitter {
  private static readonly UTF8Encoding s_utf8NoBom = new(encoderShouldEmitUTF8Identifier: false);

  private readonly IrModule _module;
  private readonly IrTypeTable _types;
  private readonly Compilation? _compilation;
  private readonly CEmitOptions _options;
  private readonly StringBuilder _sb = new(16384);
  private readonly Dictionary<string, SourceText> _sourcesByModuleName = new(StringComparer.Ordinal);
  private readonly SourceText? _rootSource;

  // Collected closure thunks: (IrFuncId, IrClosureTypeId) -> C function name.
  private readonly Dictionary<(IrFuncId FuncId, IrTypeId ClosureTypeId), string> _closureThunks = [];
  private readonly List<(IrFuncId FuncId, IrTypeId ClosureTypeId, string ThunkName)> _orderedClosureThunks = [];

  // Map from collection type ID to companion vector type IDs when present in the type table.
  private readonly Dictionary<IrTypeId, IrTypeId> _vectorByElement = [];

  private CEmitter(IrModule module, Compilation? compilation, CEmitOptions options) {
    _module = module;
    _types = module.Types;
    _compilation = compilation;
    _options = options;

    if (compilation is not null) {
      _rootSource = compilation.RootModel.Tree.Source;
      foreach (SemanticModel model in compilation.SemanticModels) {
        if (!string.IsNullOrEmpty(model.Module.Name)) {
          _sourcesByModuleName[model.Module.Name] = model.Tree.Source;
        }
      }
    }

    for (int i = 0; i < _types.Count; i++) {
      if (_types.Types[i] is IrVectorType vt) {
        _vectorByElement[vt.ElementType] = vt.Id;
      }
    }
  }

  /// <summary>UTF-8 encoding without BOM (TCC 0.9.27 rejects a UTF-8 BOM).</summary>
  public static Encoding Utf8NoBom => s_utf8NoBom;

  /// <summary>
  /// Emits complete, self-contained C99 source for <paramref name="module"/>.
  /// Runs <see cref="RcInsertPass"/> automatically if the module is still in <see cref="IrPassStage.PreRc"/>.
  /// </summary>
  public static string Emit(IrModule module, Compilation? compilation = null, CEmitOptions? options = null) {
    ArgumentNullException.ThrowIfNull(module);
    if (module.Stage == IrPassStage.PreRc) {
      RcInsertPass.Run(module);
    }

    var emitter = new CEmitter(module, compilation, options ?? new CEmitOptions());
    return emitter.EmitProgram();
  }

  private string EmitProgram() {
    CollectClosureThunks();

    EmitFileHeader();
    EmitStringPool();
    EmitForwardTypeDecls();
    EmitConcreteTypeDefs();
    EmitImmortalSingletons();
    EmitHelperPrototypes();
    EmitVTableDefinitions();
    EmitGlobals();
    EmitFunctionPrototypes();
    EmitClosureThunks();
    EmitRcAndEqHashHelperBodies();
    EmitCollectionHelperBodies();
    EmitFormattingHelperBodies();
    EmitVTableHelperBodies();
    EmitFunctionBodies();
    EmitMainEntrypoint();

    return _sb.ToString();
  }

  private void EmitFileHeader() {
    _sb.Append("/* Generated by pino C99 emitter (ticket 065). */\n");
    _sb.Append("#include \"pino_rt.h\"\n");
    _sb.Append("#include <stdio.h>\n");
    _sb.Append("#include <stdlib.h>\n");
    _sb.Append("#include <string.h>\n\n");

    // Hash mixing helper used by map/set hash functions across all key types.
    _sb.Append("static inline uint64_t pino_hash_mix64(uint64_t x) {\n");
    _sb.Append("  x ^= x >> 30;\n");
    _sb.Append("  x *= 0xBF58476D1CE4E5B9ull;\n");
    _sb.Append("  x ^= x >> 27;\n");
    _sb.Append("  x *= 0x94D049BB133111EBull;\n");
    _sb.Append("  return x ^ (x >> 31);\n");
    _sb.Append("}\n\n");

    _sb.Append("static inline uint64_t pino_hash_combine(uint64_t seed, uint64_t v) {\n");
    _sb.Append("  return seed ^ (v + 0x9E3779B97F4A7C15ull + (seed << 6) + (seed >> 2));\n");
    _sb.Append("}\n\n");

    _sb.Append("static inline uint64_t pino_hash_f64(double d) {\n");
    _sb.Append("  if (d == 0.0) {\n");
    _sb.Append("    d = 0.0;\n");
    _sb.Append("  }\n");
    _sb.Append("  uint64_t bits = 0;\n");
    _sb.Append("  memcpy(&bits, &d, sizeof bits);\n");
    _sb.Append("  return pino_hash_mix64(bits);\n");
    _sb.Append("}\n\n");

    // String builder helper used by generated formatting functions.
    _sb.Append("typedef struct PinoFmtBuf {\n");
    _sb.Append("  PinoStrBuf* buf;\n");
    _sb.Append("  int64_t len;\n");
    _sb.Append("} PinoFmtBuf;\n\n");

    _sb.Append("static void pino_fb_init(PinoFmtBuf* fb, int64_t cap) {\n");
    _sb.Append("  if (cap < 16) cap = 16;\n");
    _sb.Append("  fb->buf = pino_strbuf_alloc(cap);\n");
    _sb.Append("  fb->len = 0;\n");
    _sb.Append("}\n\n");

    _sb.Append("static void pino_fb_append_bytes(PinoFmtBuf* fb, const char* data, int64_t n) {\n");
    _sb.Append("  if (n <= 0) return;\n");
    _sb.Append("  if (fb->len + n > fb->buf->cap) {\n");
    _sb.Append("    int64_t old_cap = fb->buf->cap;\n");
    _sb.Append("    int64_t new_cap = old_cap * 2;\n");
    _sb.Append("    if (new_cap < fb->len + n) new_cap = fb->len + n;\n");
    _sb.Append("    fb->buf = (PinoStrBuf*)PINO_REALLOC(pino_cur_alloc, fb->buf,\n");
    _sb.Append("      sizeof(PinoStrBuf) + (size_t)old_cap + 1,\n");
    _sb.Append("      sizeof(PinoStrBuf) + (size_t)new_cap + 1, \"string buffer\");\n");
    _sb.Append("    fb->buf->cap = new_cap;\n");
    _sb.Append("  }\n");
    _sb.Append("  memcpy(fb->buf->data + fb->len, data, (size_t)n);\n");
    _sb.Append("  fb->len += n;\n");
    _sb.Append("}\n\n");

    _sb.Append("static void pino_fb_append_cstr(PinoFmtBuf* fb, const char* s) {\n");
    _sb.Append("  pino_fb_append_bytes(fb, s, (int64_t)strlen(s));\n");
    _sb.Append("}\n\n");

    _sb.Append("static void pino_fb_append_str_owned(PinoFmtBuf* fb, PinoString s) {\n");
    _sb.Append("  pino_fb_append_bytes(fb, s.ptr, s.byte_len);\n");
    _sb.Append("  pino_str_release(s);\n");
    _sb.Append("}\n\n");

    _sb.Append("static PinoString pino_fb_finish(PinoFmtBuf* fb) {\n");
    _sb.Append("  if (fb->len == 0) {\n");
    _sb.Append("    pino_str_release(pino_strbuf_seal(fb->buf, 0));\n");
    _sb.Append("    return PINO_STR_EMPTY;\n");
    _sb.Append("  }\n");
    _sb.Append("  return pino_strbuf_seal(fb->buf, fb->len);\n");
    _sb.Append("}\n\n");

    // Runtime stderr line printing helper for Eprintln.
    _sb.Append("static void pino_eprintln(PinoString s) {\n");
    _sb.Append("  fflush(stdout);\n");
    _sb.Append("  if (s.byte_len > 0) {\n");
    _sb.Append("    fwrite(s.ptr, 1, (size_t)s.byte_len, stderr);\n");
    _sb.Append("  }\n");
    _sb.Append("  fputc('\\n', stderr);\n");
    _sb.Append("  fflush(stderr);\n");
    _sb.Append("}\n\n");

    // UTF-8 rune iteration helpers for StrDecodeRune / StrNextBytePos.
    _sb.Append("static int32_t pino_str_decode_at(PinoString s, int64_t byte_pos) {\n");
    _sb.Append("  if (byte_pos < 0 || byte_pos >= s.byte_len) return 0;\n");
    _sb.Append("  int used = 0;\n");
    _sb.Append("  return pino_utf8_decode(s.ptr + byte_pos, s.ptr + s.byte_len, &used);\n");
    _sb.Append("}\n\n");

    _sb.Append("static int64_t pino_str_next_pos(PinoString s, int64_t byte_pos) {\n");
    _sb.Append("  if (byte_pos < 0 || byte_pos >= s.byte_len) return s.byte_len;\n");
    _sb.Append("  int used = 0;\n");
    _sb.Append("  (void)pino_utf8_decode(s.ptr + byte_pos, s.ptr + s.byte_len, &used);\n");
    _sb.Append("  return byte_pos + (used > 0 ? used : 1);\n");
    _sb.Append("}\n\n");
  }

  private void EmitStringPool() {
    if (_module.StringPool.Count == 0) {
      return;
    }

    _sb.Append("/* Interned string literals */\n");
    for (int i = 0; i < _module.StringPool.Count; i++) {
      string s = _module.StringPool[i];
      byte[] utf8 = s_utf8NoBom.GetBytes(s);
      _sb.Append("static const char pstr_").Append(i).Append("[] = ");
      AppendCBytesLiteral(utf8);
      _sb.Append(";\n");
    }

    _sb.Append('\n');
  }

  private void CollectClosureThunks() {
    foreach (IrFunction fn in _module.Functions) {
      foreach (IrBasicBlock bb in fn.Blocks) {
        foreach (IrInstruction instr in bb.Instructions) {
          if (instr is ClosureMake cm) {
            IrTypeId closTypeId = fn.Temps[cm.Dest.Index].Type;
            var key = (cm.Function, closTypeId);
            if (!_closureThunks.ContainsKey(key)) {
              string name = $"pclos_{cm.Function.Index}_c{closTypeId.Index}";
              _closureThunks[key] = name;
              _orderedClosureThunks.Add((cm.Function, closTypeId, name));
            }
          }
        }
      }
    }
  }

  // ---------------------------------------------------------------------------
  // Mangling & C type naming helpers (D-005, design §7.1)
  // ---------------------------------------------------------------------------

  private string CType(IrTypeId id) {
    IrType t = _types.GetType(id);
    return t.Kind switch {
      IrTypeKind.Void or IrTypeKind.Never => "void",
      IrTypeKind.Bool => "uint8_t",
      IrTypeKind.Int => "int64_t",
      IrTypeKind.Float => "double",
      IrTypeKind.Rune => "int32_t",
      IrTypeKind.Enum => "int32_t",
      IrTypeKind.Handle => "PinoHandle",
      IrTypeKind.String => "PinoString",
      IrTypeKind.Regex => "PinoRegex*",
      IrTypeKind.Struct => StructCName(id),
      IrTypeKind.Tuple => TupleCName(id),
      IrTypeKind.Union => t.IsRecursiveUnion ? $"{UnionCName(id)}*" : UnionCName(id),
      IrTypeKind.Vector => $"{VectorStructCName(id)}*",
      IrTypeKind.Map => $"{MapStructCName(id)}*",
      IrTypeKind.Set => $"{SetStructCName(id)}*",
      IrTypeKind.Pool => $"{PoolStructCName(id)}*",
      IrTypeKind.Closure => "PinoClosure",
      IrTypeKind.Interface => IfaceCName(id),
      IrTypeKind.Ptr => $"{CType(((IrPtrType) t).TargetType)}*",
      IrTypeKind.Cell => $"{CellStructCName(id)}*",
      IrTypeKind.Env => $"{EnvStructCName(id)}*",
      _ => throw new InvalidOperationException($"Unsupported IR type kind '{t.Kind}'."),
    };
  }

  private string CParamType(IrTypeId typeId, IrParamOwnership ownership) {
    if (ownership == IrParamOwnership.Mut) {
      return CType(typeId);
    }

    IrType t = _types.GetType(typeId);
    return t.PassByConstPtr ? $"const {CType(typeId)}*" : CType(typeId);
  }

  private bool IsPassByConstPtr(IrTypeId typeId, IrParamOwnership ownership) =>
      ownership != IrParamOwnership.Mut && _types.GetType(typeId).PassByConstPtr;

  private bool IsVoidOrNever(IrTypeId typeId) =>
      _types.GetType(typeId).Kind is IrTypeKind.Void or IrTypeKind.Never;

  private string StructCName(IrTypeId id) => $"pt_s_{id.Index}_{Sanitize(_types.GetType(id).Name)}";

  private string TupleCName(IrTypeId id) => $"pt_tup_{id.Index}";

  private string UnionCName(IrTypeId id) => $"pt_u_{id.Index}_{Sanitize(_types.GetType(id).Name)}";

  private bool IsStringVector(IrTypeId vecTypeId) =>
      _types.GetType(vecTypeId) is IrVectorType vt && vt.ElementType == _types.String;

  private string VectorStructCName(IrTypeId id) =>
