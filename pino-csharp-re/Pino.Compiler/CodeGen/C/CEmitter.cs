  private string IfaceCName(IrTypeId id) => $"pt_iface_{id.Index}_{Sanitize(_types.GetType(id).Name)}";

  private string VTableStructCName(IrTypeId ifaceId) => $"pt_vt_{ifaceId.Index}";

