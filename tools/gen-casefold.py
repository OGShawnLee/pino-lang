#!/usr/bin/env python3
"""
Generates the simple Unicode case-folding tables (Unicode CaseFolding C + S)
for both Pino runtimes:
  - runtime-re/pino_casefold.h
  - pino-csharp-re/Pino.Vm/Regex/UnicodeCaseFold.cs

Written from scratch for Pino Lang (MIT). Run from the repository root:
  python tools/gen-casefold.py
"""
from pathlib import Path
import unicodedata


def compute_simple_casefold():
    """Return (canonical_map, next_map) for all Unicode scalar values."""
    # Step 1: Extract C (common, 1-to-1 casefold) and S (simple, 1-to-1 lower
    # when full casefold expands to multiple code points).
    raw_fold = {}
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        cf = ch.casefold()
        if len(cf) == 1:
            target = ord(cf)
            if target != cp:
                raw_fold[cp] = target
        else:
            lo = ch.lower()
            if len(lo) == 1 and ord(lo) != cp:
                raw_fold[cp] = ord(lo)

    # Step 2: Union-find equivalence classes so folding is strictly symmetric
    # and transitive (every class has one canonical representative = min folded target).
    parent = {}

    def find(x):
        while parent.get(x, x) != x:
            parent[x] = parent.get(parent[x], parent[x])
            x = parent[x]
        return x

    def union(a, b):
        ra, rb = find(a), find(b)
        if ra != rb:
            # Prefer canonical folded target (or smaller code point) as root.
            if ra < rb:
                parent[rb] = ra
            else:
                parent[ra] = rb

    for src, dst in raw_fold.items():
        union(src, dst)

    classes = {}
    for cp in set(raw_fold.keys()) | set(raw_fold.values()):
        root = find(cp)
        classes.setdefault(root, []).append(cp)

    canonical_map = {}
    next_map = {}
    for members in classes.values():
        members.sort()
        # Pick the folded representative: if any member has a raw_fold target in
        # the class that doesn't itself fold further, use it; otherwise smallest.
        canon = members[0]
        for m in members:
            if m not in raw_fold:
                canon = m
                break
        for i, m in enumerate(members):
            if m != canon:
                canonical_map[m] = canon
            next_map[m] = members[(i + 1) % len(members)]

    return canonical_map, next_map


def compress_runs(mapping):
    """
    Compress {cp: target} into sorted non-overlapping runs:
      (lo, hi, stride, delta)
    meaning for every r in [lo, hi] with (r - lo) % stride == 0,
    mapped(r) = r + delta.
    """
    items = sorted(mapping.items())
    runs = []
    i = 0
    n = len(items)
    while i < n:
        cp, target = items[i]
        delta = target - cp
        if i + 1 < n:
            cp2, target2 = items[i + 1]
            stride = cp2 - cp
            if target2 - cp2 == delta and stride in (1, 2):
                hi = cp2
                j = i + 2
                while j < n and items[j][0] == hi + stride and items[j][1] - items[j][0] == delta:
                    hi = items[j][0]
                    j += 1
                runs.append((cp, hi, stride, delta))
                i = j
                continue
        runs.append((cp, cp, 1, delta))
        i += 1
    return runs


def verify_runs(runs, expected):
    """Verify binary-search lookup over runs matches expected dict for all 0..0x10FFFF."""
    # Check strictly sorted & disjoint
    for i in range(1, len(runs)):
        assert runs[i - 1][1] < runs[i][0], f"Overlap at {i}: {runs[i-1]} vs {runs[i]}"

    def lookup(r):
        lo, hi = 0, len(runs) - 1
        while lo <= hi:
            mid = (lo + hi) >> 1
            r_lo, r_hi, stride, delta = runs[mid]
            if r < r_lo:
                hi = mid - 1
            elif r > r_hi:
                lo = mid + 1
            else:
                if stride == 1 or ((r - r_lo) % stride) == 0:
                    return r + delta
                return r
        return r

    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        want = expected.get(cp, cp)
        got = lookup(cp)
        assert got == want, f"Mismatch at U+{cp:04X}: got U+{got:04X}, want U+{want:04X}"


def write_c_header(path: Path, uni_version: str, canon_runs, next_runs):
    lines = [
        "/*",
        f" * pino_casefold.h - simple Unicode case-folding tables (Unicode {uni_version}).",
        " *",
        " * GENERATED by tools/gen-casefold.py — do not edit by hand.",
        " * UTF-8 without BOM, LF line endings, plain C99.",
        " */",
        "#ifndef PINO_CASEFOLD_H",
        "#define PINO_CASEFOLD_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        f'#define PINO_UNICODE_CASEFOLD_VERSION "{uni_version}"',
        "",
        "typedef struct PinoFoldRun {",
        "  int32_t lo;",
        "  int32_t hi;",
        "  int32_t delta;",
        "  uint8_t stride;",
        "} PinoFoldRun;",
        "",
        f"static const PinoFoldRun pino_cf_canonical[{len(canon_runs)}] = {{",
    ]
    for lo, hi, stride, delta in canon_runs:
        lines.append(f"  {{0x{lo:04X}, 0x{hi:04X}, {delta}, {stride}u}},")
    lines.append("};")
    lines.append(f"#define PINO_CF_CANONICAL_LEN {len(canon_runs)}")
    lines.append("")
    lines.append(f"static const PinoFoldRun pino_cf_orbit[{len(next_runs)}] = {{")
    for lo, hi, stride, delta in next_runs:
        lines.append(f"  {{0x{lo:04X}, 0x{hi:04X}, {delta}, {stride}u}},")
    lines.append("};")
    lines.append(f"#define PINO_CF_ORBIT_LEN {len(next_runs)}")
    lines.append("")
    lines.append("static inline int32_t pino_fold_lookup(const PinoFoldRun* table, size_t len, int32_t r) {")
    lines.append("  size_t lo = 0;")
    lines.append("  size_t hi = len;")
    lines.append("  while (lo < hi) {")
    lines.append("    size_t mid = lo + ((hi - lo) >> 1);")
    lines.append("    if (r < table[mid].lo) {")
    lines.append("      hi = mid;")
    lines.append("    } else if (r > table[mid].hi) {")
    lines.append("      lo = mid + 1;")
    lines.append("    } else {")
    lines.append("      if (table[mid].stride == 1u || ((r - table[mid].lo) % (int32_t)table[mid].stride) == 0) {")
    lines.append("        return r + table[mid].delta;")
    lines.append("      }")
    lines.append("      return r;")
    lines.append("    }")
    lines.append("  }")
    lines.append("  return r;")
    lines.append("}")
    lines.append("")
    lines.append("/* Canonical simple Unicode case fold for any scalar value. */")
    lines.append("static inline int32_t pino_casefold_canonical(int32_t r) {")
    lines.append("  if (r < 0x80) {")
    lines.append("    return (r >= 'A' && r <= 'Z') ? (r + 32) : r;")
    lines.append("  }")
    lines.append("  return pino_fold_lookup(pino_cf_canonical, PINO_CF_CANONICAL_LEN, r);")
    lines.append("}")
    lines.append("")
    lines.append("/* Next rune in the sorted simple case-folding equivalence cycle (returns r if singleton). */")
    lines.append("static inline int32_t pino_casefold_next(int32_t r) {")
    lines.append("  return pino_fold_lookup(pino_cf_orbit, PINO_CF_ORBIT_LEN, r);")
    lines.append("}")
    lines.append("")
    lines.append("#endif /* PINO_CASEFOLD_H */")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def write_cs_file(path: Path, uni_version: str, canon_runs, next_runs):
    lines = [
        f"// GENERATED by tools/gen-casefold.py (Unicode {uni_version}) — do not edit by hand.",
        "namespace Pino.Vm.Regex;",
        "",
        "/// <summary>Simple one-to-one Unicode case-folding tables (Unicode CaseFolding C + S).</summary>",
        "internal static class UnicodeCaseFold {",
        f'  public const string UnicodeVersion = "{uni_version}";',
        "",
        "  internal readonly record struct FoldRun(int Lo, int Hi, int Delta, byte Stride);",
        "",
        "  internal static readonly FoldRun[] CanonicalRuns = [",
    ]
    for lo, hi, stride, delta in canon_runs:
        lines.append(f"    new(0x{lo:04X}, 0x{hi:04X}, {delta}, {stride}),")
    lines.append("  ];")
    lines.append("")
    lines.append("  internal static readonly FoldRun[] OrbitRuns = [")
    for lo, hi, stride, delta in next_runs:
        lines.append(f"    new(0x{lo:04X}, 0x{hi:04X}, {delta}, {stride}),")
    lines.append("  ];")
    lines.append("")
    lines.append("  public static int Canonical(int rune) {")
    lines.append("    if ((uint) rune < 0x80u) {")
    lines.append("      return rune is >= 'A' and <= 'Z' ? rune + 32 : rune;")
    lines.append("    }")
    lines.append("")
    lines.append("    return Lookup(CanonicalRuns, rune);")
    lines.append("  }")
    lines.append("")
    lines.append("  public static int NextInOrbit(int rune) => Lookup(OrbitRuns, rune);")
    lines.append("")
    lines.append("  private static int Lookup(FoldRun[] table, int rune) {")
    lines.append("    int lo = 0;")
    lines.append("    int hi = table.Length;")
    lines.append("    while (lo < hi) {")
    lines.append("      int mid = lo + ((hi - lo) >> 1);")
    lines.append("      FoldRun run = table[mid];")
    lines.append("      if (rune < run.Lo) {")
    lines.append("        hi = mid;")
    lines.append("      } else if (rune > run.Hi) {")
    lines.append("        lo = mid + 1;")
    lines.append("      } else {")
    lines.append("        return run.Stride == 1 || ((rune - run.Lo) % run.Stride) == 0 ? rune + run.Delta : rune;")
    lines.append("      }")
    lines.append("    }")
    lines.append("")
    lines.append("    return rune;")
    lines.append("  }")
    lines.append("}")
    lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main():
    root = Path(__file__).resolve().parent.parent
    uni_version = unicodedata.unidata_version
    canonical_map, next_map = compute_simple_casefold()

    # Verify ASCII invariant: for r < 0x80, canonical(r) == lowercase(r)
    for r in range(0x80):
        want = r + 32 if ord("A") <= r <= ord("Z") else r
        got = canonical_map.get(r, r)
        assert got == want, f"ASCII canonical invariant broken at U+{r:04X}: got U+{got:04X}"

    # Canonical table only needs r >= 0x80 because ASCII is handled inline.
    non_ascii_canon = {k: v for k, v in canonical_map.items() if k >= 0x80}
    canon_runs = compress_runs(non_ascii_canon)
    next_runs = compress_runs(next_map)

    verify_runs(canon_runs, non_ascii_canon)
    verify_runs(next_runs, next_map)

    # Verify key examples
    assert canonical_map[ord("Ñ")] == ord("ñ")
    assert canonical_map[ord("Á")] == ord("á")
    assert canonical_map[ord("ẞ")] == ord("ß")
    assert canonical_map[0x017F] == ord("s")
    assert canonical_map[0x212A] == ord("k")

    c_path = root / "runtime-re" / "pino_casefold.h"
    cs_path = root / "pino-csharp-re" / "Pino.Vm" / "Regex" / "UnicodeCaseFold.cs"
    write_c_header(c_path, uni_version, canon_runs, next_runs)
    write_cs_file(cs_path, uni_version, canon_runs, next_runs)
    print(
        f"Generated Unicode {uni_version} case-folding tables: "
        f"{len(canon_runs)} canonical runs, {len(next_runs)} orbit runs."
    )


if __name__ == "__main__":
    main()
