using System.Text;

namespace pino_csharp.tests.Conformance;

public class ConformanceTests {
  public static IEnumerable<object[]> AllCases() {
    foreach (var casePath in ConformanceRunner.DiscoverCases()) {
      foreach (var engine in Enum.GetValues<ConformanceEngine>()) {
        yield return new object[] { engine, casePath };
      }
    }
  }

  [Theory]
  [MemberData(nameof(AllCases))]
  public void RunCase(ConformanceEngine engine, string caseRelativePath) {
    var known = ConformanceRunner.FindKnownFailure(engine, caseRelativePath);
    if (known is { IsCrash: true }) {
      return; // crash-marked: skip running so the test host cannot crash
    }

    var verdict = ConformanceRunner.RunAndJudge(engine, caseRelativePath);

    if (known != null) {
      if (verdict.Passed) {
        Assert.Fail($"Known failure now passes: remove '{known.Line}' from {known.File}");
      }
      return; // listed and still failing: expected
    }

    if (!verdict.Passed) {
      Assert.Fail($"[{engine}] {caseRelativePath}: {verdict.Detail}");
    }
  }

  /// <summary>
  /// Regenerates conformance/STATUS.md. Only runs when PINO_CONFORMANCE_STATUS=1.
  /// Counts a case as passed only when the engine meets the expectation (known failures count as not passed).
  /// </summary>
  [Fact]
  public void GenerateStatusReport() {
    if (System.Environment.GetEnvironmentVariable("PINO_CONFORMANCE_STATUS") != "1") return;

    var engines = Enum.GetValues<ConformanceEngine>();
    var passed = new SortedDictionary<string, int[]>(StringComparer.Ordinal);
    var totals = new SortedDictionary<string, int>(StringComparer.Ordinal);

    foreach (var casePath in ConformanceRunner.DiscoverCases()) {
      var feature = ConformanceRunner.FeatureOf(casePath);
      if (!passed.ContainsKey(feature)) {
        passed[feature] = new int[engines.Length];
        totals[feature] = 0;
      }
      totals[feature]++;
      for (int i = 0; i < engines.Length; i++) {
        var known = ConformanceRunner.FindKnownFailure(engines[i], casePath);
        if (known is { IsCrash: true }) continue;
        if (ConformanceRunner.RunAndJudge(engines[i], casePath).Passed) passed[feature][i]++;
      }
    }

    var sb = new StringBuilder();
    sb.Append("# Conformance Status\n\n");
    sb.Append("Generated by `GenerateStatusReport` (see `conformance/README.md`). Cells are `passed/total`; known failures count as not passed.\n\n");
    sb.Append("| Feature | TreeWalk | VM | C | ReVm | ReC |\n");
    sb.Append("| :--- | :--- | :--- | :--- | :--- | :--- |\n");
    foreach (var feature in passed.Keys) {
      sb.Append($"| {feature} ");
      for (int i = 0; i < engines.Length; i++) {
        sb.Append($"| {passed[feature][i]}/{totals[feature]} ");
      }
      sb.Append("|\n");
    }

    File.WriteAllText(Path.Combine(ConformanceRunner.ConformanceDir, "STATUS.md"), sb.ToString(), new UTF8Encoding(false));
  }
}
